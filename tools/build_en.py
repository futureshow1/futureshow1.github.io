#!/usr/bin/env python3
"""Buduje en/index.html z index.html: ta sama strona (Stream), domyślnie po angielsku,
własny adres https://futureshow.pl/en/ (indeksowalny), angielskie meta, hreflang, ścieżki ../.
Uruchamiać po każdej zmianie index.html:  python3 tools/build_en.py"""
import re, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
def sub1(old, new, count=1):
    global s
    assert old in s, f"nie znaleziono: {old[:60]}"
    s = s.replace(old, new, count)
sub1('<html lang="pl">', '<html lang="en">')
sub1('<title>FutureShow — portal wiedzy i zabawy: portale, gry, śledztwa</title>',
     '<title>FutureShow — knowledge &amp; play: interactive portals, games, investigations</title>')
sub1('<meta name="description" content="Portal wiedzy i zabawy dla ciekawych świata: interaktywne portale, gry i śledztwa — kino, historia, nauka, dane. Bez reklam i bez kont.">',
     '<meta name="description" content="Knowledge and play for the curious: interactive portals, games and investigations — cinema, history, science, data. Free, no ads, no accounts. Silent film, animation history, avant-garde cinema, Polish jazz, the Polish parliament and more.">')
sub1('<meta name="description" content="Katalog interaktywnych portali, symulacji i śledztw studia FutureShow — przeglądaj jak w serwisie streamingowym.">', '')
sub1('<link rel="canonical" href="https://futureshow.pl/">', '<link rel="canonical" href="https://futureshow.pl/en/">')
sub1('<link rel="alternate" hreflang="x-default" href="https://futureshow.pl/">', '<link rel="alternate" hreflang="x-default" href="https://futureshow.pl/">')
sub1('<meta property="og:title" content="FutureShow — portal wiedzy i zabawy">', '<meta property="og:title" content="FutureShow — knowledge &amp; play">')
sub1('<meta property="og:description" content="Interaktywne portale, gry i śledztwa — kino, historia, nauka, dane. Bez reklam i bez kont.">',
     '<meta property="og:description" content="Interactive portals, games and investigations — cinema, history, science, data. No ads, no accounts.">')
sub1('<meta property="og:url" content="https://futureshow.pl/">', '<meta property="og:url" content="https://futureshow.pl/en/">')
# ścieżki względne → ../
for a, b in [('href="favicon-32.png"', 'href="../favicon-32.png"'), ('href="apple-touch-icon.png"', 'href="../apple-touch-icon.png"'),
             ('const ASSET="stream/assets/";', 'const ASSET="../stream/assets/";'), ('href="./"', 'href="./"')]:
    sub1(a, b)
s = s.replace('href="studio/#contact"', 'href="../studio/#contact"').replace('href="studio/"', 'href="../studio/"').replace('href="downloads.html"', 'href="../downloads.html"').replace('href="szukaj/"', 'href="../szukaj/?lang=en"').replace('src="cookie-consent.js?v=2"', 'src="../cookie-consent.js?v=2"')
# domyślny język: zawsze EN na /en/
sub1('let LANG = store.get("lang") || store.get("fs-lang") || "pl";', 'let LANG = "en";')
s = s.replace('<!doctype html>', '<!doctype html>\n<!-- generated by tools/build_en.py from ../index.html — do not edit by hand -->', 1)
open(os.path.join(ROOT, "en", "index.html"), "w", encoding="utf-8").write(s)
left = re.findall(r'(?:src|href)="(?!https?:|//|mailto:|data:|#|\.\./|\./|\$)[^"]+"', s)
print("en/index.html zapisany;", len(s), "bajtów; pozostałe ścieżki względne:", left)
